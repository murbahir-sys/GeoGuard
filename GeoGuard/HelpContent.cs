# Что делает GeoGuard
GeoGuard следит за вашим внешним IP-адресом и разрешает выбранным приложениям работать **только в одной стране**. В любой другой стране, а также пока страна не подтверждена, эти приложения немедленно закрываются.
С правами администратора GeoGuard дополнительно закрывает им сеть вне VPN: если VPN откажет, приложение не выйдет в интернет напрямую.

# Быстрый старт
1. Откройте настройки: двойной щелчок по значку GeoGuard в трее.
2. На вкладке «Защита» выберите страну, в которой приложениям разрешено работать.
3. Добавьте приложения: нажмите «Обзор…» и выберите .exe-файл (тогда работает и файрвол) или введите имя процесса точно как в Диспетчере задач, без .exe.
4. Включите свой VPN. На вкладке «Сеть» раскройте список «VPN-адаптер» и выберите адаптер вашего VPN.
5. Нажмите «Применить» или «Сохранить». Защита начинает работать сразу.

# Как это работает
## Определение страны
GeoGuard запрашивает страну у трёх независимых сервисов геолокации. Приложения разрешены, только если **все** ответившие сервисы назвали выбранную страну. Если мнения расходятся, это считается несовпадением: так приложение не получит «чужую» страну от собственной базы.
Программа бережёт бесплатные лимиты сервисов: к сервису с суточным лимитом обращается не чаще раза в 2 минуты, а сервис, попросивший подождать, не беспокоит 15 минут. В это время решают остальные сервисы.

## Подтверждение
При запуске программы GeoGuard сначала определяет страну и только потом действует по настройкам: совпала — приложения работают, не совпала — закрываются. Если страну не удалось получить два раза подряд, приложения закрываются.
После смены сети, сбоя проверки или смены страны в настройках страна считается неподтверждённой, и приложения закрыты. Разрешение возвращается после двух совпавших проверок подряд — обычно через 2–3 секунды. Несовпадение фиксируется по первой же проверке.

## VPN-адаптер
GeoGuard работает с любым VPN, который создаёт в Windows сетевой адаптер: WireGuard, OpenVPN, AmneziaVPN, Proton VPN, встроенные VPN-подключения Windows и другие. Адаптер вашего VPN выбирается на вкладке «Сеть»: похожие на VPN адаптеры идут в списке первыми и помечены.
Как понять, какой адаптер ваш: включите VPN и раскройте список — адаптер VPN будет без пометки «отключён»; выключите VPN — пометка появится. Можно ввести и часть имени или описания адаптера, несколько вариантов — через «;».
Выбранный адаптер нужен для двух вещей: только через него приложениям разрешён выход в сеть (файрвол), и его отключение GeoGuard замечает мгновенно. Если адаптер не выбран, страна всё равно проверяется, но файрвол не работает, а отключение VPN замечается только при очередной проверке страны.

## Что считается сменой сети
GeoGuard реагирует, только когда мог измениться внешний IP: VPN-адаптер включился, выключился или сменил адрес, либо изменился адаптер со шлюзом (кабель, Wi-Fi, точка доступа). Запуск и остановка WSL, Docker и виртуальных машин ничего не закрывают: их внутренние сети на внешний IP не влияют.

## Файрвол
С правами администратора для каждого приложения из списка, у которого известен путь к .exe, создаётся блокирующее правило Брандмауэра Windows:
- страна подтверждена — закрыты все интернет-интерфейсы, **кроме VPN-адаптера**;
- страна не подтверждена или чужая — закрыты все интерфейсы.
Правила не затрагивают сам VPN и другие программы. Они остаются при выключении компьютера и при сбое программы и продолжают защищать до следующего запуска GeoGuard.

# Значок в трее
- **Зелёный** — страна подтверждена, приложения разрешены.
- **Красный** — страна не совпадает с выбранной, приложения закрываются.
- **Серый** — страна ещё не определена или подтверждается.
Двойной щелчок открывает настройки, правая кнопка — меню.

# Вопросы и ответы
**Почему закрылось моё приложение?** Либо страна не совпала с выбранной, либо сменилась сеть (например, переподключился VPN), и страна ещё не подтверждена. Когда страна подтвердится, приложение можно запустить снова. Закрытые приложения сами не перезапускаются.

**Я запустил WSL или Docker — что-нибудь закроется?** Нет. Их внутренние сети не влияют на внешний IP и не учитываются.

**Страна верная, но приложение не выходит в сеть. Почему?** При включённом файрволе приложение получает сеть только через VPN-адаптер. Проверьте, что VPN включён и на вкладке «Сеть» выбран именно его адаптер. Если VPN не используется, снимите галочку файрвола.

**Какой VPN подходит?** Любой, который создаёт сетевой адаптер (так работают почти все VPN-клиенты). Программы, работающие только как прокси, адаптера не создают — с ними GeoGuard проверяет страну, но файрвол по адаптеру не работает; у многих таких программ есть режим TUN, который создаёт адаптер.

**Приложение из списка не закрывается, хотя страна другая.** Скорее всего, имя процесса указано неточно. Удалите запись и добавьте приложение через «Обзор…».

**Как временно отключить защиту?** Меню значка в трее → «Выход». Приложения перестанут закрываться, а правила файрвола будут удалены.

**Как удалить правила файрвола, если программа не запускается?** Запустите `GeoGuard.exe --remove-rules` (потребуется подтверждение администратора) или удалите программу через «Приложения и возможности».

**Можно ли добавить в список сам VPN-клиент?** Нет. Известные VPN-клиенты (AmneziaVPN, WireGuard, OpenVPN, Proton VPN, NordVPN, Mullvad и другие) защищены: GeoGuard не закроет их и не создаст для них правил, чтобы не отключить сам VPN.

# Командные ключи
- `--no-elevate` — не запрашивать права администратора (файрвол недоступен).
- `--remove-rules` — удалить правила файрвола и автозапуск.
- `--selftest-firewall` — проверить работу файрвола на этом компьютере.
- `--silent` — служебные команды без окон сообщений.

